const messages: Record<Locale, Record<MessageKey, string>> = { en, zh };

export function t(key: MessageKey, locale: Locale = getLocale(), vars?: Record<string, string | number>): string {
  let text = messages[locale][key] ?? messages.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function applyDomI18n(): void {
  if (typeof document === "undefined") return;
  const locale = getLocale();
  document.documentElement.lang = locale === "zh" ? "zh-Hant" : "en";
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n as MessageKey | undefined;
    if (key) el.textContent = t(key, locale);
  });
  document.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder as MessageKey | undefined;
    if (key) el.placeholder = t(key, locale);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria as MessageKey | undefined;
    if (key) el.setAttribute("aria-label", t(key, locale));
  });
}

